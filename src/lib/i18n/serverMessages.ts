export const translateServerMessage = (message: string | null | undefined, t: TFn): string => {
    if (!message) {
        return "";
    }

    const exact = EXACT[message];

    if (exact) {
        return t(exact);
    }

    for (const [pattern, key] of PATTERNS) {
        const match = message.match(pattern);

        if (match) {
            return t(key, { ...match.groups });
        }
    }

    return message;
};
